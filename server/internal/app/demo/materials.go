package demo

import (
	"context"

	"github.com/babakapaa/lodestar/server/internal/app"
	"github.com/babakapaa/lodestar/server/internal/core/auth"
	"github.com/babakapaa/lodestar/server/internal/modules/navigator"
)

func seedMaterials(ctx context.Context, core app.Core, teacher auth.Principal, courseID string) error {
	materials := navigator.NewMaterialService(core.Kernel)
	for _, in := range []navigator.MaterialInput{
		{
			Title:     "Строение клетки",
			Reference: "Демо-университет. Основы биологии, лекция 1.",
			Text: `Клетка — основная единица строения и жизнедеятельности всех живых организмов. Клетка животного состоит из плазматической мембраны, цитоплазмы с органоидами и ядра.

Плазматическая мембрана отделяет содержимое клетки от внешней среды. Она состоит из двойного слоя фосфолипидов и белков и избирательно пропускает вещества: воду, ионы, питательные вещества.

Ядро хранит наследственную информацию в виде ДНК. Внутри ядра находится ядрышко, где собираются рибосомы. Ядро окружено двойной ядерной оболочкой с порами.

Митохондрии обеспечивают клетку энергией. В них идёт клеточное дыхание, в ходе которого образуется АТФ. У митохондрий есть собственная ДНК.

Эндоплазматическая сеть бывает шероховатой и гладкой. На шероховатой сети располагаются рибосомы и синтезируются белки, гладкая участвует в синтезе липидов.

Аппарат Гольджи сортирует и упаковывает белки и липиды, а лизосомы расщепляют ненужные вещества и старые органоиды.`,
		},
		{
			Title:     "Обмен веществ",
			Reference: "Демо-университет. Основы биологии, лекция 2.",
			Text: `Обмен веществ, или метаболизм, — совокупность химических реакций в клетке. Он включает два противоположных процесса: катаболизм и анаболизм.

Катаболизм — расщепление сложных веществ до простых с выделением энергии. Пример — клеточное дыхание: глюкоза окисляется до углекислого газа и воды, а энергия запасается в молекулах АТФ.

Анаболизм — синтез сложных веществ из простых с затратой энергии. Пример — синтез белков на рибосомах и фотосинтез у растений.

Ферменты ускоряют реакции обмена веществ. Каждый фермент работает с определённым веществом и при определённой температуре и кислотности.`,
		},
	} {
		if _, err := materials.Add(ctx, teacher, courseID, in); err != nil {
			return err
		}
	}
	return nil
}
